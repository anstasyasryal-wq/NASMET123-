// Helper to find the current canonical hour prayer based on real current time
export function getCurrentLiturgicalHour(): LiturgicalHourPrayer {
  const now = new Date();
  const currentMinutes = now.getHours() * 60 + now.getMinutes();

  // 00:00 - 05:00 -> Midnight
  // 05:00 - 08:30 -> First hour (Dawn)
  // 08:30 - 11:00 -> Third hour
  // 11:00 - 14:00 -> Sixth hour (Noon)
  // 14:00 - 17:00 -> Ninth hour (Afternoon)
  // 17:00 - 20:30 -> Eleventh hour (Sunset)
  // 20:30 - 23:59 -> Twelfth hour (Compline)

  if (currentMinutes >= 300 && currentMinutes < 510) {
    return LITURGICAL_HOURS_DATA[0]; // First Hour
  } else if (currentMinutes >= 510 && currentMinutes < 660) {
    return LITURGICAL_HOURS_DATA[1]; // Third Hour
  } else if (currentMinutes >= 660 && currentMinutes < 840) {
    return LITURGICAL_HOURS_DATA[2]; // Sixth Hour
  } else if (currentMinutes >= 840 && currentMinutes < 1020) {
    return LITURGICAL_HOURS_DATA[3]; // Ninth Hour
  } else if (currentMinutes >= 1020 && currentMinutes < 1230) {
    return LITURGICAL_HOURS_DATA[4]; // Sunset (11th)
  } else if (currentMinutes >= 1230 && currentMinutes < 1440) {
    return LITURGICAL_HOURS_DATA[5]; // Compline (12th)
  } else {
    return LITURGICAL_HOURS_DATA[6]; // Midnight Vigil
  }
}

